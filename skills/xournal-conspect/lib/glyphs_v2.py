# ---------------------------------------------------------------- curve rendering
def _catmull(P, n=10, alpha=0.5):
    P = np.asarray(P, float)
    if len(P) < 3:
        return np.vstack([P[0] + (P[-1] - P[0]) * t for t in np.linspace(0, 1, max(2, n))])
    Q = np.vstack([2 * P[0] - P[1], P, 2 * P[-1] - P[-2]])
    out = []
    for i in range(1, len(Q) - 2):
        p0, p1, p2, p3 = Q[i - 1], Q[i], Q[i + 1], Q[i + 2]
        t0 = 0.0; t1 = t0 + max(np.linalg.norm(p1 - p0), 1e-6) ** alpha
        t2 = t1 + max(np.linalg.norm(p2 - p1), 1e-6) ** alpha; t3 = t2 + max(np.linalg.norm(p3 - p2), 1e-6) ** alpha
        for t in np.linspace(t1, t2, n, endpoint=False):
            A1 = (t1 - t) / (t1 - t0) * p0 + (t - t0) / (t1 - t0) * p1
            A2 = (t2 - t) / (t2 - t1) * p1 + (t - t1) / (t2 - t1) * p2
            A3 = (t3 - t) / (t3 - t2) * p2 + (t - t2) / (t3 - t2) * p3
            B1 = (t2 - t) / (t2 - t0) * A1 + (t - t0) / (t2 - t0) * A2
            B2 = (t3 - t) / (t3 - t1) * A2 + (t - t1) / (t3 - t1) * A3
            out.append((t2 - t) / (t2 - t1) * B1 + (t - t1) / (t2 - t1) * B2)
    out.append(P[-1])
    return np.array(out)

def render_stroke(st):
    """Split at corner points, spline each piece, slant."""
    pieces, cur = [], []
    for p in st:
        cur.append(p[:2])
        if len(p) > 2 and p[2] == "c":
            pieces.append(cur); cur = [p[:2]]
    pieces.append(cur)
    pts = []
    for pc in pieces:
        if len(pc) < 2: continue
        seg = _catmull(pc)
        pts.extend(seg if not pts else seg[1:])
    a = np.array(pts)
    a[:, 0] = a[:, 0] - a[:, 1] * math.tan(SLANT)     # y<0 above baseline -> shifted right
    return a

def build(variants=3, jitter=0.028, seed=3):
    """-> {char: [variant, ...]}, variant = {"strokes": [[(x, y)...]...], "w": advance width}.
    Variant 0 is the clean design; the others nudge control points slightly (like writing a letter twice)."""
    rng = np.random.default_rng(seed)
    out = {}
    for ch, strokes0 in G.items():
        k = WIDEN_LOWER if (ch.isalpha() and ch.islower()) else (WIDEN_UPPER if ch.isalnum() else 1.0)
        vs = []
        for v in range(variants if ch.isalnum() else 1):
            j = 0.0 if v == 0 else jitter
            strokes = [[(p[0] * k + rng.normal(0, j), p[1] + rng.normal(0, j)) + tuple(p[2:]) for p in st] for st in strokes0]
            S = [render_stroke(s) for s in strokes]
            x0 = min(0.0, min(s[:, 0].min() for s in S))
            S = [s - [x0, 0] for s in S]
            vs.append({"strokes": [s.tolist() for s in S], "w": float(max(s[:, 0].max() for s in S))})
        out[ch] = vs
    return out
